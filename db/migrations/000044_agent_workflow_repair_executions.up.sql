CREATE TABLE IF NOT EXISTS agent_workflow_repair_executions (
    execution_uuid VARCHAR(81) NOT NULL,
    plan_id VARCHAR(76) NOT NULL,
    proposal_uuid VARCHAR(71) NOT NULL,
    task_uuid VARCHAR(64) NOT NULL,
    executor_uuid VARCHAR(24) NOT NULL,
    executor_grant_version BIGINT UNSIGNED NOT NULL,
    expected_current_sha256 CHAR(64) NULL,
    target_sha256 CHAR(64) NOT NULL,
    rollback_sha256 CHAR(64) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'prepared',
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    failure_code VARCHAR(64) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (execution_uuid),
    UNIQUE KEY idx_agent_repair_execution_plan (plan_id),
    KEY idx_agent_repair_execution_task_status (task_uuid, status),
    CONSTRAINT fk_agent_repair_execution_proposal FOREIGN KEY (proposal_uuid) REFERENCES agent_workflow_repair_proposals(proposal_uuid),
    CONSTRAINT fk_agent_repair_execution_task FOREIGN KEY (task_uuid) REFERENCES agent_tasks(task_uuid),
    CONSTRAINT chk_agent_repair_execution_status CHECK (status IN ('prepared', 'executing', 'committed', 'failed', 'rolled_back')),
    CONSTRAINT chk_agent_repair_execution_window CHECK (finished_at IS NULL OR started_at IS NULL OR started_at <= finished_at),
    CONSTRAINT chk_agent_repair_execution_failure CHECK (status = 'failed' OR failure_code IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
